interface I18nState {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
}

export const useI18n = create<I18nState>()(
  persist(
    (set, get) => ({
      lang: "ru",
      setLang: (lang) => set({ lang }),
      t: (key) => STRINGS[get().lang][key] ?? key,
    }),
    {
      name: "tez-dashboard-lang",
      partialize: (state) => ({ lang: state.lang }),
    },
  ),
);
